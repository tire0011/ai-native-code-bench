[CmdletBinding()]
param(
    [string]$ProjectPath = 'workspaces/CleanArchitecture',
    [ValidatePattern('^[A-Za-z0-9][A-Za-z0-9._/-]*(:[A-Za-z0-9._-]+)?$')]
    [string]$BaseModel = 'qwen3:8b',
    [ValidateRange(4096, 65536)]
    [int]$ContextTokens = 8192,
    [switch]$SetupOnly,
    [switch]$SmokeTest
)

$ErrorActionPreference = 'Stop'
$Root = $PSScriptRoot
$OllamaUrl = 'http://127.0.0.1:11434'
$LocalModel = 'csharp-local'
$GeneratedMarker = 'Generated by ai-native-code-bench local.ps1'

function Require-Command([string]$Name) {
    $command = Get-Command $Name -ErrorAction SilentlyContinue
    if (-not $command) { throw "Required command not found in PATH: $Name" }
    return $command.Source
}

function Write-Utf8NoBom([string]$Path, [string]$Content) {
    [System.IO.File]::WriteAllText($Path, $Content, [System.Text.UTF8Encoding]::new($false))
}

function Get-OllamaTags {
    try {
        return Invoke-RestMethod -Uri "$OllamaUrl/api/tags" -TimeoutSec 2
    }
    catch {
        return $null
    }
}

function Start-LocalOllama([string]$Executable, [string]$LogDirectory) {
    New-Item -ItemType Directory -Force -Path $LogDirectory | Out-Null
    $stdout = Join-Path $LogDirectory 'server.stdout.log'
    $stderr = Join-Path $LogDirectory 'server.stderr.log'
    Write-Host 'Starting Ollama with local-only, single-model settings...'
    $process = Start-Process -FilePath $Executable -ArgumentList 'serve' `
        -WindowStyle Hidden -RedirectStandardOutput $stdout -RedirectStandardError $stderr -PassThru
    $deadline = (Get-Date).AddSeconds(45)
    do {
        $tags = Get-OllamaTags
        if ($tags) { return $tags }
        if ($process.HasExited) {
            $tail = if (Test-Path $stderr) { (Get-Content $stderr -Tail 12) -join [Environment]::NewLine } else { '' }
            throw "Ollama exited during startup (code $($process.ExitCode)). $tail"
        }
        Start-Sleep -Milliseconds 500
    } while ((Get-Date) -lt $deadline)
    throw "Ollama did not become ready at $OllamaUrl within 45 seconds"
}

$ollama = Require-Command 'ollama'
$opencode = Require-Command 'opencode'
$null = Require-Command 'dotnet'
$null = Require-Command 'dnx'

$candidate = if ([System.IO.Path]::IsPathRooted($ProjectPath)) { $ProjectPath } else { Join-Path $Root $ProjectPath }
$ProjectPath = (Resolve-Path -LiteralPath $candidate).Path
$solution = Get-ChildItem -LiteralPath $ProjectPath -Recurse -File -Include '*.sln', '*.slnx' -ErrorAction SilentlyContinue |
    Sort-Object { $_.FullName.Split([System.IO.Path]::DirectorySeparatorChar).Count }, FullName |
    Select-Object -First 1
if (-not $solution) { throw "No .sln or .slnx found below $ProjectPath" }

$instructionsPath = Join-Path $Root 'assistant/csharp.md'
$templatePath = Join-Path $Root 'assistant/opencode.template.jsonc'
$targetConfigDirectory = Join-Path $ProjectPath '.opencode'
$targetConfig = Join-Path $targetConfigDirectory 'opencode.jsonc'
if (Test-Path -LiteralPath $targetConfig) {
    $existing = Get-Content -LiteralPath $targetConfig -Raw
    if (-not $existing.Contains($GeneratedMarker)) {
        throw "Refusing to overwrite existing config: $targetConfig. Merge assistant/opencode.template.jsonc manually or choose another project copy."
    }
}

# These process settings are inherited by a server started here and by OpenCode.
# An already-running Ollama server keeps its original settings.
$env:OLLAMA_HOST = $OllamaUrl
$env:OLLAMA_NO_CLOUD = '1'
$env:OLLAMA_MAX_LOADED_MODELS = '1'
$env:OLLAMA_NUM_PARALLEL = '1'
$env:OLLAMA_KEEP_ALIVE = '30m'
$env:OLLAMA_CONTEXT_LENGTH = [string]$ContextTokens
$env:OLLAMA_FLASH_ATTENTION = '1'
$env:OLLAMA_KV_CACHE_TYPE = 'q8_0'
$env:OPENCODE_DISABLE_FREE_MODELS = '1'

$LogDirectory = Join-Path $Root 'local-results/local-assistant'
$tags = Get-OllamaTags
if ($tags) {
    Write-Warning 'Reusing the running Ollama server. Its startup environment is unchanged; restart Ollama through this script to apply all performance/local-only settings.'
}
else {
    $tags = Start-LocalOllama -Executable $ollama -LogDirectory $LogDirectory
}

$installed = @($tags.models | Where-Object { $_.name -eq $BaseModel -or $_.model -eq $BaseModel })
if (-not $installed) {
    throw "Base model '$BaseModel' is not installed. Download it explicitly with: ollama pull $BaseModel"
}

New-Item -ItemType Directory -Force -Path $LogDirectory | Out-Null
$modelFile = Join-Path $LogDirectory 'Modelfile'
$modelDefinition = @"
# Generated by local.ps1; blobs are shared with the base model.
FROM $BaseModel
PARAMETER num_ctx $ContextTokens
PARAMETER temperature 0.1
PARAMETER num_predict 4096
"@
Write-Utf8NoBom -Path $modelFile -Content ($modelDefinition + [Environment]::NewLine)
Write-Host "Creating $LocalModel from $BaseModel (context $ContextTokens)..."
& $ollama create $LocalModel -f $modelFile
if ($LASTEXITCODE -ne 0) { throw "ollama create failed with exit code $LASTEXITCODE" }

$showBody = @{ model = $LocalModel } | ConvertTo-Json -Compress
$show = Invoke-RestMethod -Uri "$OllamaUrl/api/show" -Method Post -Body $showBody -ContentType 'application/json' -TimeoutSec 15
$capabilities = @($show.capabilities)
if ('completion' -notin $capabilities -or 'tools' -notin $capabilities) {
    throw "$LocalModel must expose completion and tools capabilities; found: $($capabilities -join ', ')"
}

New-Item -ItemType Directory -Force -Path $targetConfigDirectory | Out-Null
$config = Get-Content -LiteralPath $templatePath -Raw
$config = $config.Replace('{{INSTRUCTIONS_PATH_JSON}}', (ConvertTo-Json $instructionsPath -Compress))
$config = $config.Replace('{{PROJECT_PATH_JSON}}', (ConvertTo-Json $ProjectPath -Compress))
$config = $config.Replace('{{DISPLAY_NAME_JSON}}', (ConvertTo-Json "Local C# ($BaseModel)" -Compress))
$config = $config.Replace('{{CONTEXT_TOKENS}}', [string]$ContextTokens)
Write-Utf8NoBom -Path $targetConfig -Content $config

Write-Host 'Preloading the local model; checking actual memory placement...'
$preloadBody = @{ model = $LocalModel; prompt = ''; keep_alive = '30m' } | ConvertTo-Json -Compress
$null = Invoke-RestMethod -Uri "$OllamaUrl/api/generate" -Method Post -Body $preloadBody -ContentType 'application/json' -TimeoutSec 180
& $ollama ps

Write-Host ''
Write-Host "Project:  $ProjectPath"
Write-Host "Solution: $($solution.FullName)"
Write-Host "Model:    ollama/$LocalModel (from $BaseModel)"
Write-Host "Config:   $targetConfig"
Write-Host 'Only the Ollama provider and a loopback endpoint are permitted by the generated profile. Web tools are denied.'

Push-Location $ProjectPath
try {
    if ($SmokeTest) {
        Write-Host 'Running an OpenCode local-only smoke test...'
        $smokeLog = Join-Path $LogDirectory 'opencode-smoke.jsonl'
        $smokeOutput = & $opencode run --standalone --agent build --format json --model "ollama/$LocalModel" 'Do not use tools. Reply with exactly LOCAL_OK and nothing else.' 2>&1
        $smokeExit = $LASTEXITCODE
        Write-Utf8NoBom -Path $smokeLog -Content (($smokeOutput | ForEach-Object { $_.ToString() }) -join [Environment]::NewLine)
        if ($smokeExit -ne 0 -or -not (($smokeOutput | Out-String).Contains('LOCAL_OK'))) {
            throw "OpenCode smoke test failed (exit $smokeExit); see $smokeLog"
        }
        Write-Host 'OpenCode smoke test: LOCAL_OK'
    }
    if (-not $SetupOnly) {
        & $opencode
        if ($LASTEXITCODE -ne 0) { throw "OpenCode exited with code $LASTEXITCODE" }
    }
}
finally {
    Pop-Location
}
